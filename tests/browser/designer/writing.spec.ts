import { test, expect } from './fixture'
test('notepad selection aligns a guided text box to actual paper rules',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('/design/customize?templateId=white-notepad&redirectedFrom=/design/customize')
 await expect(page.getByRole('button',{name:'Continue to Order'})).toBeVisible()
 await page.getByRole('button',{name:'Edit content',exact:true}).click()
 await expect(page.getByRole('checkbox',{name:'Guided writing'})).toBeChecked()
 await page.getByRole('textbox',{name:'Message text'}).fill('Hello from the guided text box.\nA second line.')
 await page.getByRole('button',{name:'Canvas',exact:true}).click()
 await expect(page.locator('[data-paper-type="white-notepad"]')).toBeVisible()
 await expect.poll(()=>page.locator('[data-testid="canvas-artboard"] text').count()).toBeGreaterThan(1)
 const baselines=await page.locator('[data-testid="canvas-artboard"] text').evaluateAll(nodes=>nodes.map(node=>Number(node.getAttribute('y'))+85))
 expect(baselines.every(value=>Math.abs((value-110)%30)<.001)).toBe(true)
})
test('failed online save keeps the customer in the designer with recovery',async({page})=>{
 await page.goto('/design/customize?templateId=yellow-letter&redirectedFrom=/design/customize')
 await expect(page.locator('[data-testid="canvas-artboard"] text').first()).toBeVisible()
 await page.getByRole('button',{name:'Continue to Order'}).click()
 await expect(page.getByRole('alert').filter({hasText:/writes disabled|save failed|Unable to save/i})).toBeVisible()
 await expect(page).toHaveURL(/\/design\/customize/)
 await expect(page.getByRole('button',{name:'Retry saving'})).toBeVisible()
})
test('adding a printed side updates its fee immediately without confirmation',async({page})=>{
 await page.goto('/design/customize?templateId=white-notepad&redirectedFrom=/design/customize')
 await page.getByRole('button',{name:'Show pages',exact:true}).click()
 await page.getByLabel('Mail pieces', {exact:true}).fill('1000')
 await page.getByRole('button',{name:'Add Page',exact:true}).click()
 await expect(page.getByTestId('additional-side-total')).toHaveText('$100.00')
 await expect(page.getByRole('alertdialog')).toHaveCount(0)
})
